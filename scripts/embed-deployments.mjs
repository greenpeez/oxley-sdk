import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, URL } from "node:url";
import process from "node:process";
import { MANIFEST, validateManifest } from "./deployment-manifests.mjs";

// The reviewed testnet manifest is the single source; the library bundles a verbatim copy so a client needs no file access.
// The manifest must exist and carry the release ID prefix of its slot.
const root = fileURLToPath(new URL("..", import.meta.url));
const manifest = JSON.parse(readFileSync(`${root}${MANIFEST.file}`, "utf8"));
validateManifest(manifest);
const text = `// Generated by scripts/embed-deployments.mjs from ${MANIFEST.file}. Do not edit; run \`npm run embed\`.\n\n`
  + `/** The reviewed testnet deployment (chain 99801), a verbatim copy of ${MANIFEST.file}. */\n`
  + `export const ${MANIFEST.exportName} = ${JSON.stringify(manifest, null, 2)} as const;\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(`${root}src/testnet-deployment.ts`, "utf8") !== text) { process.exitCode = 1; process.stderr.write("src/testnet-deployment.ts is stale; run npm run embed\n"); }
} else writeFileSync(`${root}src/testnet-deployment.ts`, text);
