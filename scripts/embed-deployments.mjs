import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, URL } from "node:url";
import process from "node:process";
import { MANIFESTS, validateManifest } from "./deployment-manifests.mjs";

// The reviewed testnet manifests are the single source; the library bundles a verbatim copy so `createOxleyMarkets` needs no file access.
// A required manifest that is missing fails the run. An optional one (Gen9 until its live deployment is reviewed) is reported as absent:
// its export is `undefined` and it stays out of `testnetDeployments`. Every present manifest must be the generation its slot names.
const root = fileURLToPath(new URL("..", import.meta.url));
const loaded = MANIFESTS.map(entry => {
  if (!entry.required && !existsSync(`${root}${entry.file}`)) return { entry, manifest: undefined };
  const manifest = JSON.parse(readFileSync(`${root}${entry.file}`, "utf8"));
  validateManifest(entry, manifest);
  return { entry, manifest };
});
const present = loaded.filter(item => item.manifest);
const absent = loaded.filter(item => !item.manifest);
const body = loaded.map(({ entry, manifest }) => manifest
  ? `export const ${entry.exportName} = ${JSON.stringify(manifest, null, 2)} as const;\n`
  : `// ${entry.file} is absent: ${entry.exportName} is undefined and not part of testnetDeployments until the reviewed manifest is added and \`npm run embed\` is run.\n`
    + `export const ${entry.exportName} = undefined;\n`);
const gen9 = present.some(({ entry }) => entry.generation === "gen9");
const current = gen9 ? "Gen9 is the current launch generation (the Gen8 contracts plus a launch floor cap) and Gen8 keeps serving its existing auctions"
  : "Gen8 is the current launch generation";
const text = `// Generated by scripts/embed-deployments.mjs from deployments/*.json. Do not edit; run \`npm run embed\`.\n\n${body.join("\n")}\n`
  + `/** Reviewed testnet generations, oldest first: flat-fee and Gen3 hold markets, ${current}. Gen2 is not bundled: its 14 auctions all failed, so its curve holds no market (checked 2026-10-29). */\n`
  + `export const testnetDeployments = [${present.map(({ entry }) => entry.exportName).join(", ")}] as const;\n`;
for (const { entry } of absent) process.stderr.write(`${entry.file} is absent: ${entry.exportName} is undefined and not bundled\n`);
if (process.argv.includes("--check")) {
  if (readFileSync(`${root}src/testnet-deployments.ts`, "utf8") !== text) { process.exitCode = 1; process.stderr.write("src/testnet-deployments.ts is stale; run npm run embed\n"); }
} else writeFileSync(`${root}src/testnet-deployments.ts`, text);
