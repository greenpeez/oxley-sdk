import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, URL } from "node:url";
import process from "node:process";

// The reviewed testnet manifests are the single source; the library bundles a verbatim copy so `createOxleyMarkets` needs no file access.
const root = fileURLToPath(new URL("..", import.meta.url));
const manifests = [
  ["flatFeeTestnetDeployment", "deployments/elysium-testnet.json"],
  ["gen3TestnetDeployment", "deployments/elysium-testnet-gen3.json"],
  ["gen8TestnetDeployment", "deployments/elysium-testnet-gen8.json"],
];
const body = manifests.map(([name, path]) => `export const ${name} = ${JSON.stringify(JSON.parse(readFileSync(`${root}${path}`, "utf8")), null, 2)} as const;\n`);
const text = `// Generated by scripts/embed-deployments.mjs from deployments/*.json. Do not edit; run \`npm run embed\`.\n\n${body.join("\n")}\n`
  + `/** Reviewed testnet generations, oldest first: flat-fee and Gen3 hold markets, Gen8 is the current launch generation. Gen2 is not bundled: its 14 auctions all failed, so its curve holds no market (checked 2026-10-29). */\n`
  + `export const testnetDeployments = [${manifests.map(([name]) => name).join(", ")}] as const;\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(`${root}src/testnet-deployments.ts`, "utf8") !== text) { process.exitCode = 1; process.stderr.write("src/testnet-deployments.ts is stale; run npm run embed\n"); }
} else writeFileSync(`${root}src/testnet-deployments.ts`, text);
